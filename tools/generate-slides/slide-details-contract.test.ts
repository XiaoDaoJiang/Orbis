import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../..')
const require = createRequire(resolve(root, 'apps/slides/package.json'))
const { parse, compileScript, compileTemplate, compileStyle } = require('vue/compiler-sfc')
const filename = resolve(root, 'apps/slides/components/SlideDetails.vue')
const source = await readFile(filename, 'utf8')
const { descriptor, errors } = parse(source, { filename })
assert.deepEqual(errors, [])
const script = compileScript(descriptor, { id: 'slide-details-test' })
const template = compileTemplate({ source: descriptor.template.content, filename, id: 'slide-details-test', compilerOptions: { bindingMetadata: script.bindings } })
assert.deepEqual(template.errors, [])
const css = compileStyle({ source: descriptor.styles[0].content, filename, id: 'data-v-slide-details-test', scoped: true })
assert.deepEqual(css.errors, [])
assert.match(css.code, /body:has\(\.z-modal\.left-0\) \.orbis-detail-mobile-trigger\s*\{ display: none;/, 'Overview rule must hide only the floating trigger, never the body')
assert.ok(!source.includes('v-html'), 'Details must render escaped static slot content, never raw HTML injection')
assert.match(source, /<slot\s*\/>/)
assert.match(source, /<Teleport v-if="interactive" to="body">/)
assert.match(source, /<dialog[\s\S]*?:aria-labelledby="headingId"/)
assert.match(source, /\.showModal\(\)/, 'Native modal supplies focus containment and inert background')
assert.match(source, /closeButton\.value\?\.focus/)
assert.match(source, /activeTrigger\?\.isConnected/)
assert.match(source, /activeTrigger\.focus\(\{ preventScroll: true \}\)/)
assert.match(source, /event\.key === 'Escape'/)
assert.match(source, /lockShortcuts\(\)/)
assert.match(source, /unlockShortcuts\?\.\(\)/)
assert.match(source, /router\.afterEach\(\(\) => close\(false\)\)/)
assert.match(source, /onBeforeUnmount\(\(\) =>/)
assert.match(source, /removeRouteHook\(\)/)
assert.match(source, /currentSlideNo\.value === \$page\.value/)
assert.match(source, /\$renderContext\.value === 'slide'/)
assert.match(source, /currentRoute\.value\.name === 'play'/)
assert.match(source, /max-height: 85vh;\s*max-height: 85svh;/)
assert.match(source, /orbis-detail-dialog\[open\] \{ display: flex; flex-direction: column;/)
assert.match(source, /orbis-detail-content \{ min-height: 0; flex: 1 1 auto; overflow: auto;/, 'Only the content scrolls; the close button remains visible')
assert.match(source, /orbis-detail-header \{ display: flex; flex: 0 0 auto;/)
assert.match(source, /max-height: min\(120px, 20svh\); overflow: auto;/, 'Long titles remain fully accessible without consuming the landscape viewport')
assert.match(source, /scrollContent\.value\.scrollTop = 0/)
assert.match(source, /<div ref="scrollContent"[\s\S]*?<footer[\s\S]*?<\/footer>\s*<\/div>/, 'Reader link belongs to scrollable content')
assert.match(source, /font: 17px\/1\.75/)
assert.match(source, /orbis-detail-mobile-trigger[\s\S]*?min-height: 44px;/)
assert.match(source, /:href="readingHref"/)
assert.match(source, /@media \(max-width: 980px\), \(max-height: 600px\)/, 'Unscaled controls cover tablet and short landscape viewports')
assert.match(source, /padding-block: 4px;/, 'Two lines at 14px/1.5 plus padding and border fit within 52px')
assert.match(source, /@media \(min-width: 641px\) and \(max-width: 980px\), \(min-width: 641px\) and \(max-height: 600px\)/, 'Wide compact viewports use one toolbar row')
assert.match(source, /left: max\(112px, calc\(env\(safe-area-inset-left\) \+ 112px\)\);/)
assert.match(source, /right: max\(190px, calc\(env\(safe-area-inset-right\) \+ 190px\)\);/)
assert.match(source, /max-width: calc\(100vw - 302px\);/)
assert.match(source, /padding-bottom: 2px; font: 730 23px\/34px/, 'Integer title line height avoids fractional two-line overflow')
assert.match(source, /font-size: 21px; line-height: 30px;/, 'Compact landscape title also uses integer line height')
assert.match(source, /@media print/)
console.log('Slide details SFC compilation and accessibility contracts passed')
